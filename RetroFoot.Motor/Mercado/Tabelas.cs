using System;
using System.Collections.Generic;

namespace RetroFoot.Motor.Mercado;

public static class Tabelas
{
    // DS:0300: 6 linhas de 6 bytes, uma por dezena da forca media (0-9 ... 50-59): quantos G,
    // D, M, A a equipa quer, um byte sem uso e o total. Com forca media >= 60 o jogo le alem
    // da tabela (os textos "Ficheiro invalido", "Ficheiro nao encontrado", uma tabela de cores
    // e, de DS:038E a DS:078D, a tabela do CRC-32); copiados aqui para dar o mesmo resultado
    // (saves editados com jogadores de forca 9999 chegam a ler a tabela do CRC).
    static readonly byte[] PlantelIdeal = Montar();

    static byte[] Montar()
    {
        byte[] ds =
        {
            0x03, 0x08, 0x07, 0x03, 0x00, 0x16, 0x03, 0x08, 0x07, 0x04, 0x00, 0x16,
            0x03, 0x08, 0x08, 0x05, 0x00, 0x17, 0x04, 0x08, 0x08, 0x05, 0x00, 0x18,
            0x04, 0x09, 0x08, 0x05, 0x00, 0x19, 0x04, 0x09, 0x08, 0x05, 0x00, 0x1a,
            0x46, 0x69, 0x63, 0x68, 0x65, 0x69, 0x72, 0x6f, 0x20, 0x69, 0x6e, 0x76,
            0xe1, 0x6c, 0x69, 0x64, 0x6f, 0x00, 0x46, 0x69, 0x63, 0x68, 0x65, 0x69,
            0x72, 0x6f, 0x20, 0x6e, 0xe3, 0x6f, 0x20, 0x65, 0x6e, 0x63, 0x6f, 0x6e,
            0x74, 0x72, 0x61, 0x64, 0x6f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x80, 0x00, 0x00, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0x00, 0xff, 0x00,
            0x00, 0x00, 0x80, 0x00, 0x80, 0x00, 0x80, 0x00, 0x00, 0x00, 0xff, 0xff,
            0xff, 0x00, 0xc0, 0xc0, 0xc0, 0x00, 0x00, 0x80, 0x80, 0x00, 0x80, 0x80,
            0x80, 0x00, 0x80, 0x80, 0x00, 0x00, 0xff, 0x00, 0xff, 0x00, 0x00, 0x80,
            0x00, 0x00, 0xff, 0xff, 0x00, 0x00, 0xff, 0xff, 0xff, 0x00,
        };
        var b = new List<byte>(ds[..0x8E]);
        // a tabela do CRC-32 (polinomio 0xEDB88320), 256 LongInts
        for (uint n = 0; n < 256; n++)
        {
            uint c = n;
            for (int k = 0; k < 8; k++) c = (c & 1) != 0 ? 0xEDB88320 ^ c >> 1 : c >> 1;
            b.AddRange(BitConverter.GetBytes(c));
        }
        return b.ToArray();
    }

    internal static byte Ideal(short dezena, int i) => PlantelIdeal[dezena * 6 + i];

    // a linha k (forca media div 10) de DS:0300, lida como o jogo le
    public static byte[] LinhaPlantelIdeal(short k) => PlantelIdeal.AsSpan(k * 6, 6).ToArray();
}
